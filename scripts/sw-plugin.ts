// Build plugin that emits the offline service worker (Requirements 8.3, 8.8).
//
// After Vite has produced the bundle, this plugin writes `dist/sw.js`. The
// worker precaches every emitted build file and every public file as relative,
// same-origin paths, and serves only those. It lives outside src/ because the
// worker source has to call `fetch`, which the source scan forbids under src/.
// `scripts/airgap-scan.mjs --dist` skips `sw.js` and only that file (8.7).

import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import type { Plugin, ResolvedConfig } from 'vite'

/** File name of the worker at the top of the output directory. */
export const SERVICE_WORKER_FILE = 'sw.js'

/** Prefix of every BaudVault cache name. Activation deletes older caches with this prefix. */
export const CACHE_PREFIX = 'baudvault-'

/** Output files that are never precached: the worker itself and Netlify's header rules. */
const EXCLUDED_FILES: ReadonlySet<string> = new Set([SERVICE_WORKER_FILE, '_headers'])

/** One file in the output directory, with its path relative to that directory. */
export interface BuildFile {
  fileName: string
  source: string | Uint8Array
}

export interface PrecacheManifest {
  /** `baudvault-` followed by a hash of the precached file names and contents. */
  cacheName: string
  /** Relative paths, resolved against the worker URL. `./` holds index.html. */
  urls: string[]
}

/**
 * Throws unless `fileName` is a plain relative path inside the output
 * directory. Such a path can only resolve to the worker's own origin.
 */
function assertRelative(fileName: string): void {
  const segments = fileName.split('/')
  const plain =
    fileName.length > 0 &&
    !fileName.startsWith('/') &&
    !/[\\:?#]/.test(fileName) &&
    segments.every((s) => s !== '' && s !== '.' && s !== '..')
  if (!plain) throw new Error(`sw-plugin: refusing to precache non-relative path ${JSON.stringify(fileName)}`)
}

/** Builds the precache list and versioned cache name for the given output files. */
export function precacheManifest(files: readonly BuildFile[]): PrecacheManifest {
  const byName = new Map<string, BuildFile>()
  for (const file of files) {
    if (EXCLUDED_FILES.has(file.fileName)) continue
    assertRelative(file.fileName)
    byName.set(file.fileName, file)
  }
  if (!byName.has('index.html')) throw new Error('sw-plugin: the build has no index.html to precache')

  const names = [...byName.keys()].sort()
  const hash = createHash('sha256')
  for (const name of names) {
    const contentHash = createHash('sha256').update(byName.get(name)!.source).digest('hex')
    hash.update(`${name}\0${contentHash}\n`)
  }

  // Netlify may redirect /index.html to /, and a navigation cannot be answered
  // with a redirected response, so the page is precached under the scope root.
  const urls = names.map((name) => (name === 'index.html' ? './' : name))
  return { cacheName: CACHE_PREFIX + hash.digest('hex').slice(0, 16), urls }
}

/** Returns the service worker source for a precache manifest. */
export function renderServiceWorker(manifest: PrecacheManifest): string {
  return `// BaudVault offline service worker. Generated by scripts/sw-plugin.ts; do not edit.
// It precaches same-origin build files and serves only those (Requirements 8.3, 8.8).
'use strict';

const CACHE_NAME = ${JSON.stringify(manifest.cacheName)};
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const PRECACHE = ${JSON.stringify(manifest.urls, null, 2)};

const ORIGIN = self.location.origin;
const ROOT_URL = new URL('./', self.location.href).href;
const INDEX_URL = new URL('index.html', self.location.href).href;
const PRECACHE_URLS = new Set(
  PRECACHE.map((p) => new URL(p, self.location.href)).filter((u) => u.origin === ORIGIN).map((u) => u.href),
);

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll([...PRECACHE_URLS])));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names.filter((n) => n.startsWith(CACHE_PREFIX) && n !== CACHE_NAME).map((n) => caches.delete(n)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

/** Answers from the cache, or from the network for the same precached URL on a miss. */
function fromPrecache(key) {
  return caches
    .open(CACHE_NAME)
    .then((cache) => cache.match(key))
    .then((cached) => cached || fetch(key));
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== ORIGIN) return;

  const path = url.origin + url.pathname;
  let key = null;
  if (path === ROOT_URL || path === INDEX_URL) key = ROOT_URL;
  else if (PRECACHE_URLS.has(path) && url.search === '') key = path;
  else if (request.mode === 'navigate') key = ROOT_URL;
  if (key === null || !PRECACHE_URLS.has(key)) return;

  event.respondWith(fromPrecache(key));
});
`
}

/** Lists every file under `dir` as a forward-slash relative path with its bytes. */
function readTree(dir: string): BuildFile[] {
  const files: BuildFile[] = []
  const walk = (current: string, prefix: string): void => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name
      const full = path.join(current, entry.name)
      if (entry.isDirectory()) walk(full, relative)
      else if (entry.isFile()) files.push({ fileName: relative, source: readFileSync(full) })
    }
  }
  walk(dir, '')
  return files
}

/** Vite plugin that emits `sw.js` with the precache list for the build. */
export function offlineServiceWorker(): Plugin {
  let config: ResolvedConfig | undefined
  return {
    name: 'baudvault:offline-service-worker',
    apply: 'build',
    enforce: 'post',
    configResolved(resolved) {
      config = resolved
    },
    generateBundle: {
      order: 'post',
      handler(_options, bundle) {
        const files: BuildFile[] = Object.values(bundle).map((output) => ({
          fileName: output.fileName,
          source: output.type === 'chunk' ? output.code : output.source,
        }))
        // Vite copies public/ into the output directory outside the bundle.
        const publicDir = config?.publicDir
        if (config?.build.copyPublicDir && publicDir && existsSync(publicDir)) {
          const bundled = new Set(files.map((f) => f.fileName))
          files.push(...readTree(publicDir).filter((f) => !bundled.has(f.fileName)))
        }
        this.emitFile({
          type: 'asset',
          fileName: SERVICE_WORKER_FILE,
          source: renderServiceWorker(precacheManifest(files)),
        })
      },
    },
  }
}
